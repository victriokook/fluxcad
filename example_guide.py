from PySide import QtCore, QtWidgets as W
from i18n import tr
import example_tools

def content(key):
    source = example_tools.source_path(key)
    guide = source.parent / 'README.md'
    csv = source.with_suffix('.csv')
    return dict(source=str(source), guide=guide.read_text(encoding='utf-8-sig') if guide.is_file() else tr('説明ファイルはありません。', 'No guide is available.'), csv_path=str(csv) if csv.is_file() else '', csv=csv.read_text(encoding='utf-8-sig') if csv.is_file() else tr('この使用例にはCSVはありません。「パラメータを変更」で寸法を確認できます。', 'No CSV accompanies this example. Inspect dimensions in Change Parameters.'))

def show(ws):
    dialog = W.QDialog(ws.main)
    dialog.setObjectName('FluxExampleGuide')
    dialog.setWindowTitle(tr('使用例のガイド', 'Example Guide'))
    dialog.resize(760, 560)
    dialog.setMinimumSize(480, 360)
    layout = W.QVBoxLayout(dialog)
    choice = W.QComboBox()
    choice.setObjectName('FluxGuideChoice')
    for item in example_tools.CATALOG:
        choice.addItem(tr(item[2], item[3]), item[0])
    layout.addWidget(choice)
    path = W.QLabel()
    path.setObjectName('FluxGuideSource')
    path.setWordWrap(True)
    path.setTextInteractionFlags(QtCore.Qt.TextSelectableByMouse)
    layout.addWidget(path)
    tabs = W.QTabWidget()
    guide = W.QTextBrowser()
    guide.setObjectName('FluxGuideText')
    guide.setOpenLinks(False)
    guide.setOpenExternalLinks(False)
    tabs.addTab(guide, tr('説明', 'Guide'))
    csv_page = W.QWidget()
    csv_layout = W.QVBoxLayout(csv_page)
    csv_path = W.QLabel()
    csv_path.setObjectName('FluxGuideCSVPath')
    csv_path.setWordWrap(True)
    csv_path.setTextInteractionFlags(QtCore.Qt.TextSelectableByMouse)
    csv_layout.addWidget(csv_path)
    csv = W.QPlainTextEdit()
    csv.setObjectName('FluxGuideCSV')
    csv.setReadOnly(True)
    csv_layout.addWidget(csv)
    tabs.addTab(csv_page, 'CSV')
    layout.addWidget(tabs)
    note = W.QLabel(tr('作業コピーを開くには「ファイル」→「使用例を作業コピーで開く」を選びます。CSVの読み込みは「パラメータを変更」で行います。', 'Use File → Open Example Working Copy to create a model copy. Import CSV through Change Parameters.'))
    note.setWordWrap(True)
    layout.addWidget(note)
    buttons = W.QDialogButtonBox(W.QDialogButtonBox.Close)
    buttons.button(W.QDialogButtonBox.Close).setText(tr('閉じる', 'Close'))
    buttons.rejected.connect(dialog.reject)
    layout.addWidget(buttons)
    def fill():
        data = content(choice.currentData())
        path.setText(data['source'])
        guide.setMarkdown(data['guide'])
        csv_path.setText(data['csv_path'])
        csv.setPlainText(data['csv'])
    choice.currentIndexChanged.connect(lambda *args: fill())
    fill()
    dialog.exec_()
